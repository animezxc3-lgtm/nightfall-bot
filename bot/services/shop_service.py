def _fmt(amount: int) -> str:
    return f"{amount:,}".replace(",", " ")


def shop_overview() -> str:
    return (
        "🛒 Магазин имущества\n\n"
        "Категории:\n"
        "🏠 `лл дом` — жильё\n"
        "🚗 `лл машина` — автомобили\n"
        "📱 `лл телефон` — телефоны\n\n"
        "Покупка: `лл дом <номер>`, `лл машина <номер>`, `лл телефон <номер>`\n"
        "Продажа: `лл продать дом|машину|телефон`"
    )


def category_text(category: str) -> str:
    items = PROPERTY_ITEMS.get(category, [])
    if not items:
        return "Категория не найдена."
    lines = [f"{CATEGORY_NAMES[category]}\n"]
    for i, (name, price, emoji) in enumerate(items, 1):
        lines.append(f"{i}. {emoji} {name} — {_fmt(price)} 🪙")
    lines.append(
        f"\n💡 Покупка: `лл { 'дом' if category == 'housing' else 'машина' if category == 'car' else 'телефон' } <номер>`"
    )
    return "\n".join(lines)


def buy_by_index(user_id: int, category: str, index: int) -> str:
    items = PROPERTY_ITEMS.get(category)
    if not items or not (1 <= index <= len(items)):
        return "Такого предмета нет в этой категории."

    name, price, emoji = items[index - 1]
    user = db.get_user(user_id)
    if not user:
        return "Профиль не найден."

    field = CATEGORY_DB_FIELDS[category]
    current = user[field] or "Отсутствует"
    if current != "Отсутствует":
        return "У тебя уже есть имущество этой категории. Сначала продай его."

    coins = int(user["coins"] or 0)
    if coins < price:
        return (
            f"Недостаточно монет.\n"
            f"Цена: {_fmt(price)} 🪙\n"
            f"Твой баланс: {_fmt(coins)} 🪙"
        )

    ok = db.update_coins(user_id, -price)
    if not ok:
        return "Недостаточно монет."

    db.update_user_field(user_id, field, name)
    return (
        f"Покупка совершена!\n"
        f"{emoji} {name}\n"
        f"💰 Потрачено: {_fmt(price)} 🪙"
    )


def sell(user_id: int, category: str) -> str:
    field = CATEGORY_DB_FIELDS.get(category)
    if not field:
        return "Неизвестная категория."

    user = db.get_user(user_id)
    if not user:
        return "Профиль не найден."

    current = user[field] or "Отсутствует"
    if current == "Отсутствует":
        return "У тебя нет имущества этой категории."

    # Возврат 50%
    refund = 0
    for name, price, _ in PROPERTY_ITEMS.get(category, []):
        if name == current:
            refund = price // 2
            break

    db.update_user_field(user_id, field, "Отсутствует")
    if refund > 0:
        db.update_coins(user_id, refund)

    return (
        f"Имущество продано: {current}\n"
        f"💰 Возврат: {_fmt(refund)} 🪙 (50%)"
    )
